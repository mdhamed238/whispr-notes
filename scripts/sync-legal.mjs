// Embeds content/legal/*.md into content/legal/index.ts so the app can show
// them offline. Run `yarn legal` after editing any of the Markdown files.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'content', 'legal');
const docs = ['privacy', 'terms', 'data'];
const body = docs.map((d) => `  ${d}: ${JSON.stringify(readFileSync(join(dir, `${d}.md`), 'utf8'))},`).join('\n');
writeFileSync(
  join(dir, 'index.ts'),
  `// Generated by scripts/sync-legal.mjs from content/legal/*.md. Do not edit by hand.\n\nexport const LEGAL_DOCS = {\n${body}\n} as const;\n\nexport type LegalDoc = keyof typeof LEGAL_DOCS;\n`
);
console.log(`Wrote ${docs.length} legal documents to content/legal/index.ts`);
