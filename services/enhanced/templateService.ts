  /**
   * Apply template to transcription item
   */
  applyTemplate(item: EnhancedTranscriptionItem, template: ExportTemplate): string {
    let content = template.template;

    // Prepare all available variables
    const variables = {
      ...template.variables,
      // Basic item data
      transcription: item.transcription,
      date: item.createdAt.toLocaleDateString(),
      time: item.createdAt.toLocaleTimeString(),
      datetime: item.createdAt.toLocaleString(),
      duration: this.formatDuration(item.duration),
      durationSeconds: item.duration.toString(),
      category: item.category,
      tags: item.tags.join(', '),
      tagsArray: item.tags.map(tag => `"${tag}"`).join(', '),
      confidence: item.confidence ? `${Math.round(item.confidence * 100)}%` : 'N/A',
      confidenceDecimal: item.confidence?.toString() || '0',
      wordCount: item.transcription.split(/\s+/).filter(word => word.trim()).length.toString(),
      
      // Metadata
      id: item.id,
      processingTime: item.processingTime?.toFixed(1) || 'N/A',
      
      // Audio quality
      audioQuality: item.audioQuality?.overallScore ? `${Math.round(item.audioQuality.overallScore * 100)}%` : 'N/A',
      signalToNoise: item.audioQuality?.signalToNoiseRatio?.toFixed(1) || 'N/A',
      
      // Timestamps
      createdTimestamp: item.createdAt.getTime().toString(),
      isoDate: item.createdAt.toISOString(),
      
      // Calculated fields
      estimatedReadingTime: Math.ceil(item.transcription.split(/\s+/).length / 200).toString(), // ~200 WPM
      characterCount: item.transcription.length.toString(),
    };

    // Process conditional blocks first
    content = this.processConditionalBlocks(content, variables);

    // Replace template variables
    Object.entries(variables).forEach(([key, value]) => {
      const regex = new RegExp(`{{${key}}}`, 'g');
      content = content.replace(regex, value || '');
    });

    // Clean up any remaining unreplaced variables
    content = content.replace(/{{[^}]+}}/g, '');

    return content;
  }

