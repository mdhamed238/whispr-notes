  /**
   * Get all available templates
   */
  async getTemplates(): Promise<ExportTemplate[]> {
    try {
      const customTemplates = await this.getCustomTemplates();
      return [...this.builtInTemplates, ...customTemplates];
    } catch (error) {
      console.error('Failed to get templates:', error);
      return this.builtInTemplates;
    }
  }

  /**
   * Get templates for specific format
   */
  async getTemplatesForFormat(format: ExportFormat): Promise<ExportTemplate[]> {
    const allTemplates = await this.getTemplates();
    return allTemplates.filter(template => template.format === format);
  }

  /**
   * Get template by ID
   */
  async getTemplate(id: string): Promise<ExportTemplate | null> {
    const templates = await this.getTemplates();
    return templates.find(template => template.id === id) || null;
  }

  /**
   * Save custom template
   */
  async saveTemplate(template: ExportTemplate): Promise<void> {
    try {
      const customTemplates = await this.getCustomTemplates();
      
      // Check if template already exists
      const existingIndex = customTemplates.findIndex(t => t.id === template.id);
      
      if (existingIndex >= 0) {
        customTemplates[existingIndex] = template;
      } else {
        customTemplates.push(template);
      }

      await AsyncStorage.setItem(this.STORAGE_KEY, JSON.stringify(customTemplates));
    } catch (error) {
      console.error('Failed to save template:', error);
      throw error;
    }
  }

  /**
   * Delete custom template
   */
  async deleteTemplate(id: string): Promise<void> {
    try {
      const customTemplates = await this.getCustomTemplates();
      const filteredTemplates = customTemplates.filter(template => template.id !== id);
      
      await AsyncStorage.setItem(this.STORAGE_KEY, JSON.stringify(filteredTemplates));
    } catch (error) {
      console.error('Failed to delete template:', error);
      throw error;
    }
  }

